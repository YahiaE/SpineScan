create table if not exists public.albums (
    id bigint generated by default as identity primary key,
    artist text not null,
    album text not null,
    normalized_key text not null,
    discogs_release_id bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists albums_normalized_key_uidx
    on public.albums (normalized_key);

create index if not exists albums_discogs_release_id_idx
    on public.albums (discogs_release_id);

alter table public.albums enable row level security;

grant select, insert, update, delete on table public.albums to service_role;
grant usage, select on sequence public.albums_id_seq to service_role;
